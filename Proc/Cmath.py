
from typing import *
def Add(a:int,b:int)->int:
    """_summary_

    Args:
        a (int): Can be any number
        b (int): Can be any number

    Returns:
        int: Return int
    """
    return a+b

def Sub(a: int, b: int) -> int:
    """_summary_

    Args:
        a (int): Can be any number
        b (int): Can be any number

    Returns:
        int: Return int
    """
    return a - b